interface PixelIconProps {
  name: string;
  size?: number;
  className?: string;
  style?: React.CSSProperties;
}

export const PixelIcon: React.FC<PixelIconProps> = ({
  name,
  size = 16,
  className = '',
  style,
}) => {
  const pattern = PIXEL_ICONS[name] || PIXEL_ICONS.star;
  const height = pattern.length;
  const width = pattern[0].length;

  return (
    <svg
      className={`fp-icon ${className}`}
      width={size}
      height={size}
      viewBox={`0 0 ${width} ${height}`}
      shapeRendering="crispEdges"
      fill="currentColor"
      aria-hidden="true"
      style={style}
    >
      {pattern.map((row, y) =>
        [...row].map((char, x) =>
          char === '#' ? (
            <rect key={`${x}-${y}`} x={x} y={y} width={1} height={1} />
          ) : null
        )
      )}
    </svg>
  );
};
